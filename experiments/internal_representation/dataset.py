"""Load persona conversation histories for internal-representation probing.

The source is the JSONL file generated by ``generate_backgrounds``. Each row
contains ``messages`` and ground-truth values in ``persona`` (currently Gender
and Region). No synthetic placeholder conversations are generated here.
"""

from __future__ import annotations

import json
import random
from collections import defaultdict
from pathlib import Path
from typing import Any

from config import DataConfig


def _format_messages(messages: list[dict[str, str]]) -> str:
    """Format context through the final user turn for causal-state extraction.

    Messages after the final user turn cannot affect that user's hidden state in
    a causal LLM. Omitting the stored reply is exactly equivalent at the target
    token and avoids a large amount of unnecessary computation during ablation.
    """
    last_user = max(
        (index for index, message in enumerate(messages) if message.get("role") == "user"),
        default=-1,
    )
    lines: list[str] = []
    for message in messages[:last_user + 1]:
        role = message.get("role")
        content = message.get("content")
        if role not in {"system", "user", "assistant"} or not isinstance(content, str):
            raise ValueError(f"Invalid persona message: {message!r}")
        lines.append(f"{role.capitalize()}: {content}")
    return "\n".join(lines)


def _last_user_question(messages: list[dict[str, str]]) -> str:
    for message in reversed(messages):
        if message.get("role") == "user":
            return str(message.get("content", ""))
    return ""


def _select_context(messages: list[dict[str, str]], mode: str) -> list[dict[str, str]]:
    if mode == "full":
        return messages
    if mode != "gender-turn-only":
        raise ValueError(f"Unknown context mode: {mode}")
    matches = [
        message for message in messages
        if message.get("role") == "user"
        and "I really enjoy watching " in str(message.get("content", ""))
        and "how should I structure my daily routine?" in str(message.get("content", ""))
    ]
    if len(matches) != 1:
        raise ValueError(f"Expected exactly one generated Gender turn, found {len(matches)}")
    return [matches[0]]


def _load_rows(path: Path) -> list[dict[str, Any]]:
    if not path.is_file():
        raise FileNotFoundError(
            f"Persona dataset not found: {path}. Generate it first with "
            "`python -m generate_backgrounds` or pass --personas-file."
        )

    rows: list[dict[str, Any]] = []
    with path.open(encoding="utf-8-sig") as handle:
        for line_number, line in enumerate(handle, start=1):
            if not line.strip():
                continue
            try:
                row = json.loads(line)
            except json.JSONDecodeError as exc:
                raise ValueError(f"Invalid JSON on line {line_number} of {path}: {exc}") from exc
            if not isinstance(row.get("persona"), dict) or not isinstance(row.get("messages"), list):
                raise ValueError(f"Line {line_number} must contain persona and messages fields")
            rows.append(row)
    return rows


def _sample_groups(rows: list[dict[str, Any]], config: DataConfig) -> list[dict[str, Any]]:
    """Optionally apply a reproducible cap to each joint persona group."""
    if config.samples_per_group is None:
        return rows
    if config.samples_per_group < 1:
        raise ValueError("samples_per_group must be at least 1")

    groups: dict[tuple[Any, ...], list[dict[str, Any]]] = defaultdict(list)
    for row in rows:
        key = tuple(row["persona"].get(attribute) for attribute in config.attributes)
        groups[key].append(row)

    rng = random.Random(config.seed)
    sampled: list[dict[str, Any]] = []
    for key in sorted(groups, key=lambda values: tuple(str(value) for value in values)):
        group = groups[key]
        sampled.extend(group if len(group) <= config.samples_per_group else rng.sample(group, config.samples_per_group))
    return sampled


def prepare_dataset(config: DataConfig) -> dict[str, Any]:
    """Load, validate, filter and normalize the personas JSONL dataset."""
    if not config.attributes:
        raise ValueError("At least one persona attribute is required")

    source = Path(config.personas_file).expanduser().resolve()
    rows = _load_rows(source)
    available = sorted({key for row in rows for key in row["persona"]})
    unknown = [attribute for attribute in config.attributes if attribute not in available]
    if unknown:
        raise ValueError(f"Unknown persona attributes {unknown}; available attributes: {available}")

    if not config.include_partial:
        rows = [
            row for row in rows
            if all(row["persona"].get(attribute) is not None for attribute in config.attributes)
        ]
    rows = _sample_groups(rows, config)
    if not rows:
        raise ValueError("No persona rows remain after filtering")

    selected_messages = [_select_context(row["messages"], config.context_mode) for row in rows]
    dataset = {
        "conversations": [_format_messages(messages) for messages in selected_messages],
        "conversations_chat": selected_messages,
        "labels": {
            attribute: [row["persona"].get(attribute) for row in rows]
            for attribute in config.attributes
        },
        "history_ids": [row.get("history_id") for row in rows],
        "last_user_questions": [_last_user_question(messages) for messages in selected_messages],
        "source": str(source),
        "context_mode": config.context_mode,
    }

    output_dir = Path(config.data_dir)
    output_dir.mkdir(parents=True, exist_ok=True)
    output_path = output_dir / "dataset_personas.json"
    with output_path.open("w", encoding="utf-8") as handle:
        json.dump(dataset, handle, ensure_ascii=False, indent=2)
    print(f"[Dataset] Loaded {len(rows)} persona histories from {source}")
    print(f"[Dataset] Saved normalized dataset to {output_path}")
    return dataset


if __name__ == "__main__":
    from collections import Counter

    result = prepare_dataset(DataConfig())
    print(f"Total conversations: {len(result['conversations'])}")
    for name, values in result["labels"].items():
        print(f"  {name}: {dict(Counter(values))}")
